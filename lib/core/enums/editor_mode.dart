/// Defines the available editor modes.
enum EditorMode {
  /// The main editor.
  main,

  /// The paint editor.
  paint,

  /// The text editor.
  text,

  /// The crop & rotate editor.
  cropRotate,

  /// The tune editor.
  tune,

  /// The filter editor.
  filter,

  /// The blur editor.
  blur,

  /// The emoji editor.
  emoji,

  /// The sticker editor.
  sticker,

  /// The Pixelsmix shader editor.
  pixelsmix,
}

/// Defines the available sub-editor modes.
enum SubEditorMode {
  /// The paint editor.
  paint,

  /// The text editor.
  text,

  /// The crop & rotate editor.
  cropRotate,

  /// The tune editor.
  tune,

  /// The filter editor.
  filter,

  /// The blur editor.
  blur,

  /// The emoji editor.
  emoji,

  /// The sticker editor.
  sticker,

  /// The video-audio editor.
  audio,

  /// The video-clips editor.
  videoClips,

  /// The Pixelsmix tone-curve editor.
  pixelsmixCurve,

  /// The Pixelsmix HSL editor.
  pixelsmixHsl,

  /// The Pixelsmix color-balance editor.
  pixelsmixColorBalance,

  /// The Pixelsmix tone-separation editor.
  pixelsmixToneSeparation,

  /// The Pixelsmix vibrance editor.
  pixelsmixVibrance,

  /// The Pixelsmix haze editor.
  pixelsmixHaze,

  /// The Pixelsmix highlight/shadow editor.
  pixelsmixHighlightShadow,

  /// The Pixelsmix sharpen editor.
  pixelsmixSharpen,

  /// The Pixelsmix noise editor.
  pixelsmixNoise,

  /// The Pixelsmix vignette editor.
  pixelsmixVignette,

  /// The Pixelsmix filter editor (built-in LUT presets, former color matrix).
  pixelsmixFilter,

  /// The Pixelsmix LUT editor.
  pixelsmixLut,

  /// The Pixelsmix blur editor (circular / linear blur).
  pixelsmixBlur,
}
